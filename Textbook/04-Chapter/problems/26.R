# 26. Growing Perpetuities
# Mark Weinstein has been working on an advanced technology in laser eye
# surgery. His technology will be available in the near term. He anticipates
# his first annual cash flow from the technology to be $175,000, received two
# years from today. Subsequent annual cash flows will grow at 3.5 percent in
# perpetuity. What is the present value of the technology if the discount rate
# is 10 percent?

format(175e3 * (1.10)^-1 * (.1 - .035)^-1, big.mark=',')
